/** 相对当前时间生成 ISO 时间，保证“可能过期”示例在任意演示日期都成立 */
function daysAgo(days: number, hour = 10, minute = 0): string {
  const date = new Date(Date.now() - days * 24 * 60 * 60 * 1000);
  date.setHours(hour, minute, 0, 0);
  return date.toISOString();
}

