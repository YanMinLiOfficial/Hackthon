import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['src/features/journey/travelPlanner.ts'], bundle: true, write: false, format: 'esm' });
const { planDemoTravel } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const places = ['place-student-center', 'place-library-east', 'place-canteen', 'place-teaching-3', 'place-gym'].map((id) => ({ id }));
const start = places[0].id, end = places[1].id;
const defaults = { avoidStairs: true, needsRamp: true, needsElevator: false };
const ramp = planDemoTravel(places, start, end, defaults);
assert.equal(ramp.ok, true);
assert.equal(ramp.preferred.totalMeters, 420);
assert.equal(ramp.shortest.totalMeters, 100);
assert.equal(ramp.preferred.segments.some((edge) => edge.kind === 'stairs' || edge.kind === 'elevator'), false);
const elevator = planDemoTravel(places, start, end, { ...defaults, needsRamp: false, needsElevator: true });
assert.equal(elevator.preferred.totalMeters, 360);
assert.equal(elevator.preferred.segments.some((edge) => edge.kind === 'elevator'), true);
const ordinary = planDemoTravel(places, start, end, { avoidStairs: false, needsRamp: false, needsElevator: false });
assert.equal(ordinary.preferred.totalMeters, 100);
const both = planDemoTravel(places, start, end, { ...defaults, needsElevator: true });
assert.equal(both.ok, true, 'ramp and elevator together allow either accessible alternative');
assert.equal(both.preferred.totalMeters, 360);
assert.equal(planDemoTravel(places, start, start, defaults).ok, false);
assert.equal(planDemoTravel(places, 'missing', end, defaults).ok, false);
assert.equal(planDemoTravel(places, start, end, defaults, []).ok, false);
const reverse = planDemoTravel(places, end, start, defaults);
assert.equal(reverse.preferred.totalMeters, 420);
assert.equal(reverse.preferred.segments[0].from, end);
assert.equal(reverse.preferred.segments.at(-1).to, start);
for (const from of places) for (const to of places) {
  if (from.id === to.id) continue;
  assert.equal(planDemoTravel(places, from.id, to.id, defaults).ok, true);
}
const overlay = await build({ entryPoints: ['src/features/journey/components/DemoRouteOverlay.tsx'], bundle: true, write: false, format: 'esm', jsx: 'automatic' });
const { getDemoRoutePoints } = await import(`data:text/javascript;base64,${Buffer.from(overlay.outputFiles[0].text).toString('base64')}`);
const markers = [{ placeId: 'a', lng: 113, lat: 22 }, { placeId: 'b', lng: 114, lat: 23 }, { placeId: 'c' }];
assert.deepEqual(getDemoRoutePoints(markers, ['b', 'a']), [[114, 23], [113, 22]]);
assert.deepEqual(getDemoRoutePoints(markers, ['a', 'c', 'b']), [], 'missing waypoint must not be skipped');
assert.deepEqual(getDemoRoutePoints(markers, ['a', 'missing', 'b']), []);
assert.deepEqual(getDemoRoutePoints(markers, []), []);
console.log('PASS: ramp/elevator alternatives, stairs, invalid endpoints, disconnected graph, reverse routes, all campus pairs and complete ordered route coordinates');
