import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built=await build({entryPoints:['src/store/helpRequests.ts'],bundle:true,write:false,format:'esm'});
const {createLocalHelp,transitionLocalHelp,nearbyDemoVolunteers,HELP_NEEDS}=await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const base={currentUserId:'a',helpRequests:[],places:[{id:'p',coordinates:{lat:22.6,lng:114}}],
  demoUsers:[{userId:'a',role:'disabled_person'},{userId:'b',role:'volunteer'},{userId:'c',role:'volunteer'},{userId:'d',role:'institution'}]};
assert.deepEqual(nearbyDemoVolunteers(base,'p').map(x=>x.user.userId),['b','c','d']);
const input={id:'h',placeId:'p',need:HELP_NEEDS[0],message:' 请帮忙 ',now:'2026-10-11'};
const created=createLocalHelp(base,input);
assert.equal(created.helpRequests[0].message,'请帮忙');
assert.equal(createLocalHelp(created,{...input,id:'duplicate'}),created);
assert.equal(createLocalHelp(base,{...input,placeId:'invalid'}),base);
assert.equal(transitionLocalHelp(created,'h','accept','now'),created);
const volunteer={...created,currentUserId:'b'};
const accepted=transitionLocalHelp(volunteer,'h','accept','now');
assert.equal(accepted.helpRequests[0].status,'accepted');
assert.equal(accepted.helpRequests[0].volunteerId,'b');
const other={...accepted,currentUserId:'c'};
assert.equal(transitionLocalHelp(other,'h','accept','now'),other);
assert.equal(transitionLocalHelp(other,'h','complete','now'),other);
assert.equal(transitionLocalHelp(other,'h','cancel','now'),other);
assert.equal(transitionLocalHelp({...accepted,currentUserId:'a'},'h','complete','now').helpRequests[0].status,'completed');
assert.equal(transitionLocalHelp({...accepted,currentUserId:'a'},'h','cancel','now').helpRequests[0].status,'cancelled');
const institution={...created,currentUserId:'d'};
assert.equal(transitionLocalHelp(institution,'h','accept','now').helpRequests[0].status,'accepted');
assert.equal(createLocalHelp({...base,currentUserId:'b'},input).helpRequests.length,0);
assert.equal(createLocalHelp({...base,currentUserId:'d'},input).helpRequests.length,0);
assert.equal(createLocalHelp({...base,places:[{id:'p',coordinates:{}}]},input).helpRequests[0].recipientIds.length,0);
assert.equal(base.helpRequests.length,0);
console.log('PASS: local matching, duplicate prevention, requester/recipient/role guards, single assignment, completion, cancellation and unknown-coordinate handling.');
