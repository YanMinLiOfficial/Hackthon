import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({entryPoints:['src/features/ai/voice.ts'],bundle:true,write:false,format:'esm'});
const { classifyVoiceCommand, recognitionConstructor, speak, stopSpeaking } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
assert.equal(classifyVoiceCommand('请打开语音辅助功能。'), 'enable');
assert.equal(classifyVoiceCommand('关掉语音辅助'), 'disable');
assert.equal(classifyVoiceCommand('朗读回答'), 'read');
assert.equal(classifyVoiceCommand('停止朗读'), 'stop');
assert.equal(classifyVoiceCommand('如何打开语音辅助？'), 'question');
assert.equal(classifyVoiceCommand('不要打开语音辅助'), 'question');
assert.equal(classifyVoiceCommand('工学院轮椅能进入吗'), 'question');
globalThis.window = {};
assert.equal(recognitionConstructor(), undefined);
assert.equal(speak('测试'), false);
stopSpeaking();
class Recognition {}
window.webkitSpeechRecognition = Recognition;
assert.equal(recognitionConstructor(), Recognition);
let cancelled = 0;
let spoken;
globalThis.SpeechSynthesisUtterance = class {constructor(text){this.text=text;}};
window.SpeechSynthesisUtterance = globalThis.SpeechSynthesisUtterance;
window.speechSynthesis = {cancel(){cancelled++;},speak(value){spoken=value;}};
assert.equal(speak('语音辅助已开启'), true);
assert.equal(spoken.lang, 'zh-CN');
assert.equal(spoken.text, '语音辅助已开启');
stopSpeaking();
assert.equal(cancelled, 2);
console.log('PASS: voice command boundaries, unsupported browser, prefixed recognition and cancellable Chinese speech.');
